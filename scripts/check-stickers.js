await withTemp(async dir=>{
    const sub=async name=>{const path=join(dir,name);await mkdir(path);return path;};
    const image=join(dir,'image.png');
    await sharp({create:{width:200,height:100,channels:4,background:{r:255,g:0,b:0,alpha:0.5}}}).png().toFile(image);
    const still=await createSticker(image,await sub('still'),{kind:'image'});
    assert.equal(still.animated,false);
    const meta=await sharp(still.path).metadata();
    assert.equal(meta.width,512);assert.equal(meta.height,512);assert.equal(meta.hasAlpha,true);
    assert.ok(meta.exif?.includes(Buffer.from('UntrueBot')));
    const exif=JSON.parse(stickerExif(new Date(2026,10,24,12)).subarray(22).toString());
    assert.equal(exif['sticker-pack-publisher'],'24/11/2026');
    assert.equal(exif['sticker-pack-name'],'UntrueBot');
    assert.equal(exif.author,'24/11/2026');
    assert.ok(!meta.exif.includes(Buffer.from('@')));
    assert.ok((await stat(still.path)).size<=LIMITS.staticBytes);
    const {data}=await sharp(still.path).ensureAlpha().raw().toBuffer({resolveWithObject:true});
    assert.ok(data[3]>0,'default crop fills square without adding padding');
    const stillOut=await convertWebp(still.path,await sub('png'));
    assert.equal(stillOut.kind,'image');assert.equal((await sharp(stillOut.path).metadata()).hasAlpha,true);
    const video=join(dir,'motion.mp4');
    await run(ffmpeg,['-hide_banner','-loglevel','error','-f','lavfi','-i','testsrc2=size=160x120:rate=12','-f','lavfi','-i','sine=frequency=440','-t','1.5','-c:v','libx264','-threads','2','-pix_fmt','yuv420p','-c:a','aac','-y',video],{timeout:30000});
    const animated=await createSticker(video,await sub('animated'),{kind:'video'});
    assert.equal(animated.animated,true);
    const am=await sharp(animated.path,{animated:true}).metadata();
    assert.ok(am.pages>1);assert.equal(am.width,512);assert.equal(am.pageHeight,512);
    assert.ok((await stat(animated.path)).size<=LIMITS.animatedBytes);
    const converted=await convertWebp(animated.path,await sub('mp4'));
    const probe=await inspectMedia(converted.path);
    const v=probe.streams.find(s=>s.codec_type==='video');
    assert.equal(v.codec_name,'h264');assert.ok(Number(v.nb_frames)>1);assert.ok(Number(probe.format.duration)>1&&Number(probe.format.duration)<2);
    const {stdout:hashes}=await run(ffmpeg,['-v','error','-i',converted.path,'-f','framemd5','-'],{timeout:15000});
    const frameHashes=hashes.split('\n').filter(s=>/^0,/.test(s)).map(s=>s.split(',').at(-1).trim());
    assert.ok(new Set(frameHashes).size>1,'animation must not collapse to a still frame');
    const gif=join(dir,'motion.gif');
    await run(ffmpeg,['-hide_banner','-loglevel','error','-i',video,'-vf','fps=8,scale=80:60','-an','-y',gif],{timeout:15000});
    const gifSticker=await createSticker(gif,await sub('gif'),{kind:'image',crop:true});
    assert.equal(gifSticker.animated,true);
    assert.equal((await sharp(gifSticker.path,{animated:true}).metadata()).pageHeight,512);
    const cropped=await createSticker(image,await sub('crop'),{kind:'image',crop:true});
    const cropRaw=await sharp(cropped.path).ensureAlpha().raw().toBuffer();
    assert.ok(cropRaw[3]>0,'crop removes transparent padding');
    const longVideo=join(dir,'long.mp4');
    await run(ffmpeg,['-hide_banner','-loglevel','error','-f','lavfi','-i','color=size=64x64:rate=5','-t','16','-c:v','libx264','-threads','2','-y',longVideo],{timeout:15000});
    await assert.rejects(createSticker(longVideo,await sub('long'),{kind:'video'}),/15 segundos/);
    const audio=await extractAudio(video,await sub('audio'));
    assert.equal((await inspectMedia(audio)).streams[0].codec_name,'mp3');
    await assert.rejects(saveBoundedStream(Readable.from([Buffer.alloc(9)]),join(dir,'too-big'),{limit:8}),/demasiado grande/);
    let called=false;
    await assert.rejects(downloadToFile({media:{fileLength:20},type:'image'},join(dir,'declared'),{limit:10,download:async()=>{called=true;}}),/demasiado grande/);
    assert.equal(called,false);
    assert.equal(soundCodecAvailable(),false,'locked upstream codec lacks sticker sound');
    assert.equal(installSoundStickerCodec(),true);
    assert.equal(soundCodecAvailable(),true);
    // Full-duration audio, including the former 5-second regression.
    const longSound=join(dir,'eight-seconds.mp4');
    await run(ffmpeg,['-hide_banner','-loglevel','error','-f','lavfi','-i','color=c=black:size=160x120:rate=30','-f','lavfi','-i','color=c=white:size=24x24:rate=30','-f','lavfi','-i','sine=frequency=440','-filter_complex','[0:v][1:v]overlay=x=mod(120*t\\,130):y=40','-t','8','-c:v','libx264','-pix_fmt','yuv420p','-threads','2','-c:a','aac','-y',longSound],{timeout:30000});
    const smooth=await createSticker(longSound,await sub('smooth'),{kind:'video'});
    assert.ok(smooth.fps>=24,'simple 30 FPS source should retain at least 24 FPS');
    assert.ok(smooth.frames>180,'old frame limit must not reject a smooth 8 second sticker');
    assert.ok(Math.abs(smooth.durationMs-8000)<100);
    const reused=await createSticker(smooth.path,await sub('reused'),{kind:'sticker'});
    assert.equal(reused.frames,smooth.frames);assert.equal(reused.durationMs,smooth.durationMs);
    const fullClip=await prepareStickerAudio(longSound,await sub('full-audio'),smooth.durationMs);
    assert.ok(fullClip.durationMs>7800&&fullClip.durationMs<=8000);
    assert.equal(fullClip.seconds,8);
    const fullVideo=await convertWebp(smooth.path,await sub('full-video'),{audioPath:fullClip.path});
    const fullProbe=await inspectMedia(fullVideo.path);
    assert.ok(Number(fullProbe.streams.find(s=>s.codec_type==='audio').duration)>7.8);
    assert.ok(Number(fullProbe.streams.find(s=>s.codec_type==='video').duration)>7.8);
    const ten=join(dir,'ten.ogg');
    await run(ffmpeg,['-v','error','-f','lavfi','-i','sine=frequency=440','-t','10','-c:a','libopus','-y',ten],{timeout:15000});
    const tenClip=await prepareStickerAudio(ten,await sub('ten'),10000);
    assert.ok(tenClip.durationMs>9800&&tenClip.durationMs<=10000);
    assert.equal(tenClip.seconds,10);
    const shortClip=await prepareStickerAudio(video,await sub('short-audio'),8000);
    assert.ok(shortClip.durationMs<2000,'do not artificially extend shorter source audio');
    // Detailed clips should fit with reasonable FPS, or fail rather than use 6 FPS.
    const complex=join(dir,'complex.mp4');
    await run(ffmpeg,['-hide_banner','-loglevel','error','-f','lavfi','-i','testsrc2=size=320x240:rate=30','-f','lavfi','-i','sine=frequency=440','-t','3','-c:v','libx264','-pix_fmt','yuv420p','-threads','2','-c:a','aac','-y',complex],{timeout:30000});
    const compressed=await createSticker(complex,await sub('complex'),{kind:'video'});
    assert.ok(compressed.animated&&compressed.bytes<=LIMITS.animatedBytes&&compressed.fps>=12);
    assert.ok(Math.abs(compressed.durationMs-3000)<=100);
    assert.deepEqual(validateWebpTimeline(await readFile(compressed.path),{independent:true}),{frames:compressed.frames,durationMs:compressed.durationMs});
    const stress=join(dir,'complex-15.mp4');
    await run(ffmpeg,['-v','error','-f','lavfi','-i','testsrc2=size=320x240:rate=30','-t','15','-c:v','libx264','-pix_fmt','yuv420p','-threads','2','-y',stress],{timeout:30000});
    let stressResult;
    try{stressResult=await createSticker(stress,await sub('stress'),{kind:'video'});}
    catch(e){assert.match(e.message,/500 KB|Tiempo|tiempo|agotó/);}
    if(stressResult){assert.ok(stressResult.fps>=12&&stressResult.bytes<=LIMITS.animatedBytes);assert.ok(stressResult.durationMs>=14900);}
    // Exercise an actual high-resolution source with detailed motion.
    const hd=join(dir,'hd.mp4');
    await run(ffmpeg,['-v','error','-f','lavfi','-i','testsrc2=size=1920x1080:rate=30','-t','2','-c:v','libx264','-preset','fast','-pix_fmt','yuv420p','-threads','2','-y',hd],{timeout:30000});
    const hdSticker=await createSticker(hd,await sub('hd'),{kind:'video'});
    assert.ok(hdSticker.fps>=12&&hdSticker.bytes<=LIMITS.animatedBytes);
    assert.deepEqual(validateWebpTimeline(await readFile(hdSticker.path),{independent:true}),{frames:hdSticker.frames,durationMs:hdSticker.durationMs});
    // Explicitly tagged PQ video exercises HDR -> SDR before WebP conversion.
    const hdr=join(dir,'hdr.mp4');
    await run(ffmpeg,['-v','error','-f','lavfi','-i','testsrc2=size=320x240:rate=24','-t','1','-vf','format=yuv420p10le','-c:v','libx265','-threads','2','-x265-params','pools=1:frame-threads=1:log-level=error:colorprim=bt2020:transfer=smpte2084:colormatrix=bt2020nc','-y',hdr],{timeout:30000});
    assert.equal((await inspectMedia(hdr)).streams[0].color_transfer,'smpte2084');
    const hdrSticker=await createSticker(hdr,await sub('hdr'),{kind:'video'});
    assert.ok(hdrSticker.animated&&hdrSticker.fps>=12);
    // High FPS long source exercises the 450-frame limit and bounded batches.
    const simple15=join(dir,'simple-15.mp4');
    await run(ffmpeg,['-hide_banner','-loglevel','error','-f','lavfi','-i','color=c=black:size=160x120:rate=30','-f','lavfi','-i','color=c=white:size=24x24:rate=30','-filter_complex','[0:v][1:v]overlay=x=mod(120*t\\,130):y=40','-t','15','-c:v','libx264','-pix_fmt','yuv420p','-threads','2','-y',simple15],{timeout:30000});
    const smooth15=await createSticker(simple15,await sub('smooth15'),{kind:'video'});
    assert.ok(smooth15.fps>=24&&smooth15.frames>300);
    assert.ok(smooth15.durationMs>=14800&&smooth15.durationMs<=15000);
    assert.deepEqual(validateWebpTimeline(await readFile(smooth15.path),{independent:true}),{frames:smooth15.frames,durationMs:smooth15.durationMs});
    assert.equal(await prepareStickerAudio(simple15,await sub('silent15'),smooth15.durationMs),null);
    const smoothRecovered=await convertWebp(smooth15.path,await sub('smooth-recovered'));
    assert.ok(Number((await inspectMedia(smoothRecovered.path)).format.duration)>=14.8);
    const longSound15=join(dir,'sound15.mp4');
    await run(ffmpeg,['-v','error','-i',simple15,'-f','lavfi','-i','sine=frequency=440','-map','0:v:0','-map','1:a:0','-t','15','-c:v','copy','-c:a','aac','-y',longSound15],{timeout:30000});
    const longClip=await prepareStickerAudio(longSound15,await sub('long-audio'),smooth15.durationMs);
    assert.ok(longClip.durationMs>=14800&&longClip.durationMs<=15000);
    assert.equal(longClip.seconds,15);
    assert.ok((await stat(longClip.path)).size<=128*1024);
    const longRecovered=await convertWebp(smooth15.path,await sub('long-recovered'),{audioPath:longClip.path});
    const lp=await inspectMedia(longRecovered.path);
    for(const kind of ['video','audio'])assert.ok(Number(lp.streams.find(s=>s.codec_type===kind).duration)>=14.8);
    const lowFps=join(dir,'low-fps-14.mp4');
    await run(ffmpeg,['-v','error','-f','lavfi','-i','color=c=black:size=160x120:rate=10','-f','lavfi','-i','color=c=white:size=24x24:rate=10','-filter_complex','[0:v][1:v]overlay=x=mod(120*t\\,130):y=40','-t','14.8','-c:v','libx264','-threads','2','-pix_fmt','yuv420p','-y',lowFps],{timeout:30000});
    const lowSticker=await createSticker(lowFps,await sub('low-fps'),{kind:'video'});
    assert.ok(lowSticker.animated&&lowSticker.bytes<=LIMITS.animatedBytes);
    assert.ok(Math.abs(lowSticker.durationMs-14800)<=100);
    assert.deepEqual(validateWebpTimeline(await readFile(lowSticker.path),{independent:true}),{frames:lowSticker.frames,durationMs:lowSticker.durationMs});
    const lowRecovered=await convertWebp(lowSticker.path,await sub('low-fps-recovered'));
    assert.ok(Number((await inspectMedia(lowRecovered.path)).format.duration)>=14.6);
    const stationary=join(dir,'stationary.mp4');
    await run(ffmpeg,['-v','error','-f','lavfi','-i','color=size=128x128:rate=30','-f','lavfi','-i','sine=frequency=440','-t','3','-c:v','libx264','-threads','2','-c:a','aac','-y',stationary],{timeout:15000});
    const stationarySticker=await createSticker(stationary,await sub('stationary'),{kind:'video'});
    assert.equal(stationarySticker.animated,true);
    assert.ok(Math.abs(stationarySticker.durationMs-3000)<100);
    const stationaryMeta=await sharp(stationarySticker.path,{animated:true}).metadata();
    assert.equal(stationaryMeta.pages,2);
    assert.deepEqual(stationaryMeta.delay,[1500,1500]);
    assert.deepEqual(validateWebpTimeline(await readFile(stationarySticker.path),{independent:true}),{frames:2,durationMs:3000});
    assert.equal(stationaryMeta.width,512);assert.equal(stationaryMeta.pageHeight,512);
    assert.ok(stationaryMeta.exif.includes(Buffer.from('UntrueBot')));
    const stationaryClip=await prepareStickerAudio(stationary,await sub('stationary-audio'),stationarySticker.durationMs);
    assert.ok(stationaryClip.durationMs>=2900);
    const stationaryRecovered=await convertWebp(stationarySticker.path,await sub('stationary-recovery'),{audioPath:stationaryClip.path});
    const stationaryProbe=await inspectMedia(stationaryRecovered.path);
    for(const kind of ['video','audio']) assert.ok(Number(stationaryProbe.streams.find(s=>s.codec_type===kind).duration)>=2.9);
    const alphaFrame=await sharp({create:{width:512,height:512,channels:4,background:{r:200,g:10,b:10,alpha:0.5}}}).webp().toBuffer();
    const alphaAnimation=stationaryWebp(alphaFrame,{width:512,height:512,durationMs:15000,exif:stickerExif()});
    const alphaMeta=await sharp(alphaAnimation,{animated:true}).metadata();
    assert.equal(alphaMeta.pages,2);assert.equal(alphaMeta.hasAlpha,true);
    assert.deepEqual(alphaMeta.delay,[7500,7500]);
    const rgba=await sharp(alphaAnimation).ensureAlpha().raw().toBuffer();
    assert.ok(rgba[3]>0&&rgba[3]<255);
    console.log('Full 8/10/15-second audio, detailed fallback, high FPS and batched recovery verified');
    const clip=await prepareStickerAudio(video,await sub('sound'),animated.durationMs);
    assert.ok(clip);
    const audioMessage=await uploadStickerAudio({waUploadToServer:async path=>{assert.ok((await stat(path)).size>0);return {mediaUrl:'https://example.invalid/a',directPath:'/a'};}},clip);
    assert.equal(audioMessage.mimetype,'audio/ogg; codecs=opus');
    const logger=Object.fromEntries(['trace','debug','info','warn','error','fatal'].map(k=>[k,()=>{}]));logger.child=()=>logger;logger.level='silent';
    const content=await generateWAMessageContent({sticker:{url:animated.path},isAnimated:true,width:512,height:512,audioMessage},{logger,upload:async path=>{assert.ok((await stat(path)).size>0);return {mediaUrl:'https://example.invalid/s',directPath:'/s'};}});
    const sticker=content.stickerMessage;
    assert.ok(sticker.mediaKey);
    assert.ok(sticker.audioMessage?.mediaKey,'audio survives actual sticker upload builder');
    assert.equal(sticker.width,512);
    const bytes=proto.Message.StickerMessage.encode(sticker).finish();
    assert.ok(Buffer.from(bytes).includes(Buffer.from([210,1])),'wire field 26');
    const sent=generateWAMessageFromContent('123@s.whatsapp.net',{stickerMessage:sticker},{userJid:'456@s.whatsapp.net'});
    const decoded=proto.WebMessageInfo.decode(proto.WebMessageInfo.encode(sent).finish());
    assert.deepEqual(Buffer.from(decoded.message.stickerMessage.audioMessage.mediaKey),Buffer.from(audioMessage.mediaKey));
    assert.equal(decoded.message.stickerMessage.isAnimated,true);
    // Exercise group message preparation with a quoted command from a group member.
    const groupJid='120363000000000000@g.us';
    const groupMessage=generateWAMessageFromContent(groupJid,{stickerMessage:proto.Message.StickerMessage.fromObject(sticker)},{
        userJid:'456@s.whatsapp.net',
        quoted:{key:{remoteJid:groupJid,participant:'123@lid',fromMe:false,id:'test-command'},message:{conversation:'#s'}}
    });
    const groupDecoded=proto.WebMessageInfo.decode(proto.WebMessageInfo.encode(groupMessage).finish());
    assert.equal(groupDecoded.key.remoteJid,groupJid);
    assert.equal(groupDecoded.message.stickerMessage.contextInfo.stanzaId,'test-command');
    assert.equal(groupDecoded.message.stickerMessage.isAnimated,true);
    assert.deepEqual(Buffer.from(groupDecoded.message.stickerMessage.audioMessage.mediaKey),Buffer.from(audioMessage.mediaKey));
    assert.equal(groupDecoded.message.stickerMessage.audioMessage.directPath,audioMessage.directPath);
    console.log('Group and private sticker payloads preserve sound offline');
    assert.equal(proto.Message.StickerMessage.decode(proto.Message.StickerMessage.encode({width:512}).finish()).audioMessage,undefined);
    // Actual Baileys message round-trip, then a client quote with the audio omitted.
    const cache=new StickerAudioCache();
    cache.remember(groupDecoded);
    const quotedVisual={...groupDecoded.message.stickerMessage};
    delete quotedVisual.audioMessage;
    const response=proto.WebMessageInfo.decode(proto.WebMessageInfo.encode({
        key:{remoteJid:groupJid,id:'cmd',participant:'123@lid'},
        message:{extendedTextMessage:{text:'#sm',contextInfo:{stanzaId:groupDecoded.key.id,quotedMessage:{stickerMessage:quotedVisual}}}}
    }).finish());
    const target=selectMedia(response,{audioCache:cache});
    assert.equal(target.audioSource,'cache');
    assert.deepEqual(Buffer.from(target.audio.mediaKey),Buffer.from(audioMessage.mediaKey));
    const soundPath=join(dir,'recovered-sound.ogg');
    await downloadToFile({media:target.audio,type:'audio'},soundPath,{download:async(media,type)=>{
        assert.equal(type,'audio');assert.equal(media.directPath,audioMessage.directPath);
        const {createReadStream}=await import('node:fs');
        return createReadStream(clip.path);
    }});
    const soundVideo=await convertWebp(animated.path,await sub('sound-video'),{audioPath:soundPath});
    const streams=(await inspectMedia(soundVideo.path)).streams;
    assert.ok(streams.some(s=>s.codec_type==='audio'&&s.codec_name==='aac'));
    assert.ok(streams.some(s=>s.codec_type==='video'&&s.codec_name==='h264'));
    console.log('Experimental wire field 26 and audio mux verified offline; native WhatsApp playback not verified');
    console.log('Static, animated, PNG, MP4, audio, limits and actual motion verified');
});
